?>      <section id="workflows">
        <h2>12. Typical workflows</h2>
        <h3>Notating a new Pattern</h3>
        <ol>
          <li>Create a new binary, ternary or 9/8 score and enter the rhythm name.</li>
          <li>Set the instrument chooser, for example <em>Djembe 1</em>.</li>
          <li>Set the function chooser, for example <em>Accompaniment Pattern</em>, <em>Call</em> or <em>Solo 1</em>.</li>
          <li>Drag notes from the palette onto the staff.</li>
          <li>Add <strong>In</strong>, <strong>Out</strong>, <strong>Repeat</strong>, <strong>ShortBar</strong> or the triplet/quadruplet symbol if required.</li>
          <li>Save.</li>
        </ol>
        <h3>Saving and reopening</h3>
        <ol>
          <li>Use <strong>File → Save</strong> to update the current local file or <strong>Save as</strong> to create a new version.</li>
          <li>Under <strong>File → Open</strong>, select <strong>Local</strong>.</li>
          <li>Open the appropriate folder if required, select the score and load it.</li>
          <li>To open a server version, switch to <strong>Server</strong>. Loading creates a local version.</li>
        </ol>
        <h3>Exporting SVG or PDF</h3>
        <ol><li>Open <strong>File → Export</strong>.</li><li>Choose a file name and <strong>SVG</strong> or <strong>PDF</strong>.</li><li>Start the export. To print, open the PDF in the browser or operating system.</li></ol>
        <h3>Editing on iPhone</h3>
        <ol>
          <li>Open the score and turn the iPhone to landscape.</li>
          <li>For a new measure, first tap the chooser tool in the lower palette and then <strong>Insert instrument and function here</strong>.</li>
          <li>Select the instrument and Pattern type.</li>
          <li>Select a note symbol in the palette and tap its required position in the measure.</li>
          <li>Move elements directly or mark several with the selection tool.</li>
          <li>Use <strong>File → Save</strong> or <strong>Save as</strong>.</li>
        </ol>
        <h3>Checking a Pattern instantly</h3>
        <ol><li>Activate the selection box before the Pattern.</li><li>Select further Patterns if required.</li><li>Set the BPM at the top of the score.</li><li>Press Play. The selection loops and sounding notes are highlighted briefly.</li><li>Press the button again to stop.</li></ol>
        <h3>Practising a Pattern</h3>
        <ol><li>Open practice mode.</li><li>Open Pattern selection.</li><li>Select an Accompaniment.</li><li>Select and order one or more practice parts.</li><li>Set repeats or timer.</li><li>Optionally save a practice scenario for later use.</li><li>Press Play.</li></ol>
        <h3>Building an Arrangement</h3>
        <ol><li>Open Arrangement.</li><li>Drag Patterns from the Pattern library into the timeline.</li><li>Drag Patterns into the same section when they should play in parallel.</li><li>Set repeats.</li><li>Place Solos in Solo cells.</li><li>Check BPM, Swing, Feel and volumes.</li><li>Play or export as WAV.</li></ol>
      </section>
