?>      <section id="workflows">
        <h2>12. Typische Abläufe</h2>

        <h3>Ein neues Pattern notieren</h3>
        <ol>
          <li>Ein neues binäres, tenäres oder 9/8-Notenblatt anlegen und den Rhythmusnamen eintragen.</li>
          <li>Instrumenten-Chooser setzen, zum Beispiel <em>Djembe 1</em>.</li>
          <li>Funktions-Chooser setzen, zum Beispiel <em>Begleitpattern</em>, <em>Call</em> oder <em>Solo 1</em>.</li>
          <li>Noten aus der Palette auf die Notenlinien ziehen.</li>
          <li>Bei Bedarf <strong>In</strong>, <strong>Out</strong>, <strong>Wiederholung</strong>, <strong>ShortBar</strong> oder das Triolen-/Quartolenzeichen ergänzen.</li>
          <li>Speichern.</li>
        </ol>

        <h3>Speichern und wieder öffnen</h3>
        <ol>
          <li>Über <strong>Datei → Speichern</strong> die aktuelle lokale Datei aktualisieren oder mit <strong>Speichern als</strong> eine neue Fassung anlegen.</li>
          <li>Unter <strong>Datei → Öffnen</strong> die Quelle <strong>Lokal</strong> wählen.</li>
          <li>Bei Bedarf den passenden Ordner öffnen, das Notenblatt markieren und laden.</li>
          <li>Soll eine Serverfassung geöffnet werden, zur Quelle <strong>Server</strong> wechseln. Beim Laden wird eine lokale Fassung angelegt.</li>
        </ol>

        <h3>SVG oder PDF exportieren</h3>
        <ol>
          <li><strong>Datei → Exportieren</strong> öffnen.</li>
          <li>Dateinamen und <strong>SVG</strong> oder <strong>PDF</strong> wählen.</li>
          <li>Export starten. Zum Drucken anschließend die PDF-Datei im Browser oder Betriebssystem öffnen.</li>
        </ol>

        <h3>Auf dem iPhone bearbeiten</h3>
        <ol>
          <li>Notenblatt öffnen und das iPhone ins Querformat drehen.</li>
          <li>Bei einem neuen Takt zuerst in der unteren Palette das Chooser-Werkzeug und danach <strong>Instrument und Funktion hier einsetzen</strong> antippen.</li>
          <li>Instrument und Patternart in den Auswahlfeldern festlegen.</li>
          <li>In der Palette ein Notenzeichen wählen und auf die gewünschte Position im Takt tippen.</li>
          <li>Elemente bei Bedarf direkt verschieben oder mit dem Auswahlwerkzeug gemeinsam markieren.</li>
          <li>Über <strong>Datei → Speichern</strong> beziehungsweise <strong>Speichern als</strong> sichern.</li>
        </ol>

        <h3>Ein Pattern sofort prüfen</h3>
        <ol>
          <li>Das Auswahlfeld vor dem gewünschten Pattern aktivieren.</li>
          <li>Bei Bedarf weitere Pattern auswählen.</li>
          <li>Oben im Notenblatt das Tempo einstellen.</li>
          <li>Play drücken. Die Auswahl läuft als Loop und die klingenden Noten werden kurz hervorgehoben.</li>
          <li>Zum Beenden erneut auf den Button klicken.</li>
        </ol>

        <h3>Ein Pattern üben</h3>
        <ol>
          <li>Übungsmodus öffnen.</li>
          <li>Patternauswahl öffnen.</li>
          <li>Eine Begleitung auswählen.</li>
          <li>Ein oder mehrere Übungsteile auswählen und sortieren.</li>
          <li>Wiederholungen oder Timer einstellen.</li>
          <li>Optional ein Übungsszenario speichern, wenn diese Kombination später wieder gebraucht wird.</li>
          <li>Play drücken.</li>
        </ol>

        <h3>Ein Arrangement bauen</h3>
        <ol>
          <li>Arrangement öffnen.</li>
          <li>Pattern aus der Pattern-Bibliothek in die Timeline ziehen.</li>
          <li>Pattern parallel in denselben Abschnitt ziehen, wenn sie zusammen laufen sollen.</li>
          <li>Wiederholungen einstellen.</li>
          <li>Soli in Solo-Zellen ablegen.</li>
          <li>Tempo, Swing, Feel und Lautstärken prüfen.</li>
          <li>Abspielen oder als WAV exportieren.</li>
        </ol>
      </section>
